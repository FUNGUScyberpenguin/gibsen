/** Turning an incident name into something a filesystem will accept. */

/** Filesystem-safe stem derived from the incident name. */
export function slugify(name: string): string {
  const slug = name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
  return slug || 'incident';
}
